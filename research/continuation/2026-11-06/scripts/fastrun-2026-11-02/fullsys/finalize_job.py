"""Per-job evidence for the final runs (ADR-089 GĐ5/GĐ6, 2026-11-04): everything the comparisons and the thesis metrics
read from a job transcript, written next to it, so that a job can be kept without its 0.6-0.7 GB transcript.

What is read, always with the SAME functions the transcript-based tools use (compare_via_full.py patches them for gzip and
for big frames; nothing is re-implemented):
  audit       tang3/evidence/audit_vep.audit(transcript)       -> table (one row per ledger entry) and summary
  state       audit_vep.load(transcript)[2]                    -> final onlineState, travel-snapshot arcs stripped
  events      bridge_riders.event_times(transcript)            -> first passengerBoarded / passengerAlighted per rider
  moves       moves_plan.count(folder)                         -> G2 moves by plan membership
  shadow      compare_shadow.last_allocations(transcript)      -> class and score of every rider (Shadow runs)
  receipt     per frame: ordinal, direction, frameLengthBytes, frameSha256 (every frame's hash re-checked), plus the
              SHA-256 and size of the transcript file and of its uncompressed bytes
Written: evidence.json.gz (gzip, mtime 0) and EVIDENCE.sha256. Self-check before anything else happens: the evidence is
read back through evidence_reader.py and bridge_riders.rows_for / moves_plan.count / audit / shadow must give exactly what
they gave from the transcript.

--transcript keep   leave the transcript (default)
--transcript drop   after the self-check passed, remove the transcript; the receipt stays. A dropped transcript can be
                    regenerated by running the job again (the runs are deterministic): its frames must reproduce the
                    receipt hash by hash.
Usage: python -I -B finalize_job.py <job folder> <role> [--transcript keep|drop]
"""
import argparse
import base64
import gzip
import hashlib
import io
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import compare_via_full as C  # noqa: E402  (patches the readers; sets bridge_riders.CELL for vf cells)
import compare_shadow  # noqa: E402

audit_vep, bridge_riders = C.audit_vep, C.bridge_riders
sys.path.insert(0, str(C.PHASE1))
import moves_plan  # noqa: E402

EVIDENCE = "evidence.json.gz"
FORMAT = "ridebound-job-evidence-v1"


def memoize_readers() -> None:
    """Each reader reads the whole transcript (about a minute for a 512-rider job). Within this process every reader
    keeps its first result per job folder, so the transcript is read once per reader (load, event_times, moves, shadow,
    receipt: 5 passes) instead of about 15. The readers themselves are unchanged; audit() calls load() through the
    module, so it reuses the same result."""
    cache = {}

    def folder_of(path) -> pathlib.Path:
        path = pathlib.Path(path)
        return (path.parent if path.name.startswith("transcript-00") else path).resolve()

    def wrap(module, name):
        original = getattr(module, name)

        def wrapper(path):
            key = (name, folder_of(path))
            if key not in cache:
                cache[key] = original(path)
            return cache[key]
        setattr(module, name, wrapper)

    wrap(audit_vep, "load")
    wrap(audit_vep, "audit")
    wrap(bridge_riders, "event_times")
    wrap(moves_plan, "count")
    wrap(compare_shadow, "last_allocations")


def receipt(transcript: pathlib.Path) -> dict:
    frames = []
    raw = hashlib.sha256()
    raw_bytes = 0
    with gzip.open(transcript, "rb") as handle:
        for line in handle:
            raw.update(line)
            raw_bytes += len(line)
            record = json.loads(line)
            frame = base64.b64decode(record["frameBase64"])
            digest = hashlib.sha256(frame).hexdigest()
            if digest != record["frameSha256"] or len(frame) != record["frameLengthBytes"]:
                raise SystemExit(f"{transcript}: frame {record['ordinal']} does not match its record")
            frames.append([record["ordinal"], record["direction"], record["frameLengthBytes"], digest])
    if [f[0] for f in frames] != list(range(1, len(frames) + 1)):
        raise SystemExit(f"{transcript}: ordinals are not 1..n")
    return {"file": transcript.name, "fileSha256": hashlib.sha256(transcript.read_bytes()).hexdigest(),
            "fileBytes": transcript.stat().st_size, "uncompressedSha256": raw.hexdigest(),
            "uncompressedBytes": raw_bytes, "frameCount": len(frames), "frames": frames}


def extract(folder: pathlib.Path, role: str) -> dict:
    transcript = folder / "transcript-00.ndjson"   # the patched readers resolve the .gz
    table, summary = audit_vep.audit(transcript)
    if table is None:
        raise SystemExit(f"{folder}: no final checkpoint")
    _, _, state = audit_vep.load(transcript)
    boarded, alighted = bridge_riders.event_times(transcript)
    gz = folder / "transcript-00.ndjson.gz"
    return {
        "format": FORMAT, "job": folder.name, "role": role,
        "audit": {"table": [list(row) for row in table], "summary": summary},
        "finalOnlineState": state,
        "events": {"boarded": boarded, "alighted": alighted},
        "moves": moves_plan.count(folder),
        "shadowAllocations": compare_shadow.last_allocations(gz),
        "transcript": receipt(gz),
    }


def write_gzip_json(path: pathlib.Path, value) -> None:
    raw = json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")
    buffer = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buffer, compresslevel=9, mtime=0) as handle:
        handle.write(raw)
    with open(path, "xb") as out:
        out.write(buffer.getvalue())


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("folder")
    parser.add_argument("role")
    parser.add_argument("--transcript", choices=("keep", "drop"), default="keep")
    args = parser.parse_args()
    folder = pathlib.Path(args.folder).resolve()
    if json.loads((folder / "summary.json").read_text(encoding="utf-8")).get("status") != "pass":
        raise SystemExit(f"{folder}: not a passing job")
    if not folder.name.startswith(args.role + "-d"):
        raise SystemExit(f"{folder.name} is not a job of {args.role}")
    evidence_path = folder / EVIDENCE
    if evidence_path.exists():
        raise SystemExit(f"refused: {evidence_path} exists")
    memoize_readers()

    # from the transcript, with the tools' own functions
    from_transcript = {
        "rows": bridge_riders.rows_for(args.role, folder),
        "moves": moves_plan.count(folder),
        "audit": [list(row) for row in audit_vep.audit(folder / "transcript-00.ndjson")[0]],
        "shadow": compare_shadow.last_allocations(folder / "transcript-00.ndjson.gz"),
    }
    write_gzip_json(evidence_path, extract(folder, args.role))
    digest = hashlib.sha256(evidence_path.read_bytes()).hexdigest()
    with open(folder / "EVIDENCE.sha256", "x", encoding="utf-8", newline="\n") as handle:
        handle.write(f"{digest} *{EVIDENCE}\n")

    # read back through the evidence reader: the same functions must give the same values without the transcript
    import evidence_reader
    with evidence_reader.only_evidence(folder):
        from_evidence = {
            "rows": bridge_riders.rows_for(args.role, folder),
            "moves": moves_plan.count(folder),
            "audit": [list(row) for row in audit_vep.audit(folder / "transcript-00.ndjson")[0]],
            "shadow": compare_shadow.last_allocations(folder / "transcript-00.ndjson.gz"),
        }
    for key in from_transcript:
        if json.dumps(from_transcript[key], sort_keys=True) != json.dumps(from_evidence[key], sort_keys=True):
            raise SystemExit(f"{folder.name}: {key} from the evidence differs from the transcript; transcript kept")
    size = evidence_path.stat().st_size
    if args.transcript == "drop":
        (folder / "transcript-00.ndjson.gz").unlink()
    print(json.dumps({"job": folder.name, "evidenceBytes": size, "evidenceSha256": digest,
                      "riders": len(from_transcript["rows"]), "moves": from_transcript["moves"]["moves"],
                      "shadowAllocations": None if from_transcript["shadow"] is None else len(from_transcript["shadow"]),
                      "transcript": args.transcript, "selfCheck": "equal"}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
